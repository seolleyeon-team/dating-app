const fs = require('fs');
const path = 'scripts/privacy_client_scanner.py';
let content = fs.readFileSync(path, 'utf8').replace(/^\uFEFF/, '');
const oldBlock = `SENSITIVE_LOG_IDENTIFIERS = re.compile(\n    r"\\b[A-Za-z_]\\w*(uid|userId|kakaoUserId|firebaseUid|authorId|writerId|email|token|url|uri|path|sourcephotourl|error|stack|stacktrace|request|response|userinfo|nickname|user)\\w*\\b",\n    re.IGNORECASE,\n)\n`;
const newBlock = `SENSITIVE_LOG_IDENTIFIERS = re.compile(\n    r"\\b(uid|email|token|url|uri|path|sourcephotourl|error|stack|stacktrace|request|response|userinfo|nickname|user)\\b",\n    re.IGNORECASE,\n)\nSENSITIVE_IDENTITY_ALIAS = re.compile(\n    r"\\b(?:[A-Za-z_]\\w*(?:Id|UID|Uid)\\w*|uid[A-Z_]\\w*)\\b"\n)\n`;
if (!content.includes(oldBlock)) throw new Error('current sensitive identifier block not found');
content = content.replace(oldBlock, newBlock);
const marker = `def _unsafe_log_expression(expression: str) -> bool:\n`;
const helper = `def _contains_sensitive_log_identifier(value: str) -> bool:\n    return bool(\n        SENSITIVE_LOG_IDENTIFIERS.search(value)\n        or SENSITIVE_IDENTITY_ALIAS.search(value)\n    )\n\n\n`;
if (!content.includes(marker)) throw new Error('unsafe log function marker missing');
content = content.replace(marker, helper + marker);
const originalCall = 'bool(SENSITIVE_LOG_IDENTIFIERS.search(expression))';
if ((content.split(originalCall).length - 1) !== 1) throw new Error('direct identifier call count mismatch');
content = content.replace(originalCall, '_contains_sensitive_log_identifier(expression)');
const interpolationCall = 'SENSITIVE_LOG_IDENTIFIERS.search(value)';
if ((content.split(interpolationCall).length - 1) !== 2) throw new Error('interpolation identifier call count mismatch');
content = content.replace(interpolationCall, 'SENSITIVE_LOG_IDENTIFIERS.search(value)', 1);
const last = content.lastIndexOf(interpolationCall);
content = content.slice(0, last) + '_contains_sensitive_log_identifier(value)' + content.slice(last + interpolationCall.length);
fs.writeFileSync(path, content);
