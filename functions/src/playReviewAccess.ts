export function createPlayReviewAccessCallables(
  firestore: Firestore,
  authAdmin: Auth,
) {
  const secretOptions = withAppCheck({
    timeoutSeconds: 60,
    memory: "256MiB",
    secrets: [
      PLAY_REVIEW_LOGIN_ID,
      PLAY_REVIEW_PASSWORD_SCRYPT,
      PLAY_REVIEW_FIREBASE_UID,
      PLAY_REVIEW_ENABLED,
    ],
  });

  const signIn = onCall(secretOptions, async (request) => {
    const data = readCallableData(request.data);
    const loginId = normalizedText(data.loginId);
    const password = normalizedText(data.password);
    if (!loginId || loginId.length > 128 || !password || password.length > 256) {
      throw new HttpsError("invalid-argument", "Review credentials are required.");
    }

    const ipHash = reviewIpHash(request.rawRequest.ip ?? "unknown");
    await assertLoginAttemptAllowed(firestore, ipHash);

    const enabled = PLAY_REVIEW_ENABLED.value().trim().toLowerCase() === "true";
    const expectedUid = PLAY_REVIEW_FIREBASE_UID.value().trim();
    const valid = enabled &&
      expectedUid === PLAY_REVIEWER_UID &&
      fixedTimeTextEqual(loginId, PLAY_REVIEW_LOGIN_ID.value().trim()) &&
      verifyPlayReviewPassword(password, PLAY_REVIEW_PASSWORD_SCRYPT.value());
    if (!valid) {
      await recordLoginFailure(firestore, ipHash);
      throw new HttpsError("unauthenticated", "Review credentials are invalid.");
    }

    const userSnap = await firestore.collection("users").doc(expectedUid).get();
    const userData = (userSnap.data() ?? {}) as Record<string, unknown>;
    if (!userSnap.exists || !isPlayReviewUserData(userData)) {
      throw new HttpsError("failed-precondition", "Review profile is unavailable.");
    }
    await validateReviewFixtures(firestore);
    const authUser = await authAdmin.getUser(expectedUid).catch(() => null);
    if (!authUser || authUser.email || authUser.phoneNumber) {
      throw new HttpsError("failed-precondition", "Review auth account is invalid.");
    }
    await clearLoginFailures(firestore, ipHash);
    const customToken = await authAdmin.createCustomToken(expectedUid, {
      appSession: true,
      playReviewer: true,
      dataPartition: PLAY_REVIEW_PARTITION,
    });
    return { customToken, reviewerUid: expectedUid };
  });

  const prepareSession = onCall(withAppCheck({ timeoutSeconds: 60 }), async (request) => {
    const reviewer = await resolvePlayReviewUser(firestore, request.auth);
    await validateReviewFixtures(firestore);
    await resetReviewArtifacts(firestore);
    await seedReviewScenario(firestore);
    logger.info("Play review session prepared", { reviewerUid: reviewer.userId });
    return {
      ok: true,
      reviewerUid: reviewer.userId,
      fixtureVersion: REVIEW_BAMBOO_FIXTURE_VERSION,
      feedCandidateUids: [...PLAY_REVIEW_FEED_UIDS],
      blindMeetingId: REVIEW_MEETING_ID,
    };
  });

  const getFeed = onCall(withAppCheck(), async (request) => {
    const reviewer = await resolvePlayReviewUser(firestore, request.auth);
    const refs = PLAY_REVIEW_FEED_UIDS.map((uid) =>
      firestore.collection("publicProfiles").doc(uid)
    );
    const snaps = await firestore.getAll(...refs);
    const items = snaps.map((snap, index) => {
      const profile = (snap.data() ?? {}) as Record<string, unknown>;
      if (!snap.exists || !isPlayReviewFixtureData(profile)) {
        throw new HttpsError("failed-precondition", "Review feed is unavailable.");
      }
      return { uid: snap.id, rank: index + 1 };
    });
    await firestore.collection("playReviewEvents").doc(reviewer.userId)
      .collection("events").add({
        eventType: "feed_loaded",
        dataPartition: PLAY_REVIEW_PARTITION,
        createdAt: FieldValue.serverTimestamp(),
      });
    return {
      ok: true,
      dateKey: kstDateKey(),
      source: "play_review",
      items,
    };
  });

  const purchaseRefresh = onCall(withAppCheck(), async (request) => {
    const reviewer = await resolvePlayReviewUser(firestore, request.auth);
    const dateKey = kstDateKey();
    const userRef = firestore.collection("users").doc(reviewer.userId);
    const entitlementRef = userRef.collection("recommendationRefreshes").doc(dateKey);
    return firestore.runTransaction(async (tx) => {
      const [userSnap, existing] = await Promise.all([
        tx.get(userRef),
        tx.get(entitlementRef),
      ]);
      if (existing.exists) {
        return {
          ok: true,
          status: "already_purchased",
          dateKey,
          remainingHearts: Number(userSnap.get("heartBalance") ?? 0),
          displayCandidateUids: PLAY_REVIEW_FEED_UIDS.slice(3),
        };
      }
      const balance = Number(userSnap.get("heartBalance") ?? 0);
      if (!Number.isFinite(balance) || balance < 5) {
        throw new HttpsError("failed-precondition", "insufficient_hearts");
      }
      tx.update(userRef, {
        heartBalance: balance - 5,
        heartBalanceUpdatedAt: FieldValue.serverTimestamp(),
      });
      tx.create(entitlementRef, {
        status: "completed",
        product: "one_to_one_daily_refresh",
        heartCost: 5,
        displayCandidateUids: PLAY_REVIEW_FEED_UIDS.slice(3),
        dataPartition: PLAY_REVIEW_PARTITION,
        source: "play_review",
        completedAt: FieldValue.serverTimestamp(),
      });
      return {
        ok: true,
        status: "purchased",
        dateKey,
        remainingHearts: balance - 5,
        displayCandidateUids: PLAY_REVIEW_FEED_UIDS.slice(3),
      };
    });
  });

  return { signIn, prepareSession, getFeed, purchaseRefresh };
}

/** Server-side partition guard reused by normal triggers/callables. */
export function assertSameDataPartition(
  left: Record<string, unknown>,
  right: Record<string, unknown>,
): "production" | "play_review" {
  const leftPartition = dataPartitionOf(left);
  const rightPartition = dataPartitionOf(right);
  if (
    leftPartition === "invalid" ||
    rightPartition === "invalid" ||
    leftPartition !== rightPartition
  ) {
    throw new HttpsError("permission-denied", "Account partitions do not match.");
  }
  return leftPartition;
}

