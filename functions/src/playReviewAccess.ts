async function assertLoginAttemptAllowed(
  firestore: Firestore,
  ipHash: string,
): Promise<void> {
  const ref = firestore.collection("playReviewRateLimits").doc(ipHash);
  const snap = await ref.get();
  if (!snap.exists) return;
  const windowStartedAt = snap.get("windowStartedAt");
  const failures = Number(snap.get("failures") ?? 0);
  if (
    windowStartedAt instanceof Timestamp &&
    Date.now() - windowStartedAt.toMillis() < LOGIN_WINDOW_MS &&
    failures >= LOGIN_MAX_FAILURES
  ) {
    throw new HttpsError(
      "resource-exhausted",
      "Review sign-in is temporarily unavailable. Try again later.",
    );
  }
}

async function recordLoginFailure(
  firestore: Firestore,
  ipHash: string,
): Promise<void> {
  const ref = firestore.collection("playReviewRateLimits").doc(ipHash);
  await firestore.runTransaction(async (tx) => {
    const snap = await tx.get(ref);
    const started = snap.get("windowStartedAt");
    const active = started instanceof Timestamp &&
      Date.now() - started.toMillis() < LOGIN_WINDOW_MS;
    tx.set(ref, {
      failures: active ? Number(snap.get("failures") ?? 0) + 1 : 1,
      windowStartedAt: active ? started : FieldValue.serverTimestamp(),
      lastFailedAt: FieldValue.serverTimestamp(),
    }, { merge: false });
  });
}

async function clearLoginFailures(
  firestore: Firestore,
  ipHash: string,
): Promise<void> {
  await firestore.collection("playReviewRateLimits").doc(ipHash).delete()
    .catch(() => undefined);
}

export async function resolvePlayReviewUser(
  firestore: Firestore,
  auth: ReviewAuth,
): Promise<{ userId: string; data: Record<string, unknown> }> {
  const uid = normalizedText(auth?.uid);
  if (!uid || uid !== PLAY_REVIEWER_UID) {
    throw new HttpsError("permission-denied", "Play review access is required.");
  }
  if (
    auth?.token?.playReviewer !== true ||
    auth.token.dataPartition !== PLAY_REVIEW_PARTITION ||
    auth.token.appSession !== true
  ) {
    throw new HttpsError("permission-denied", "Play review access is required.");
  }
  const snap = await firestore.collection("users").doc(uid).get();
  const data = (snap.data() ?? {}) as Record<string, unknown>;
  if (!snap.exists || !isPlayReviewUserData(data)) {
    throw new HttpsError("failed-precondition", "Review profile is unavailable.");
  }
  return { userId: uid, data };
}

async function validateReviewFixtures(firestore: Firestore): Promise<void> {
  const refs = PLAY_REVIEW_FIXTURE_UIDS.flatMap((uid) => [
    firestore.collection("users").doc(uid),
    firestore.collection("publicProfiles").doc(uid),
  ]);
  const snaps = await firestore.getAll(...refs);
  for (let index = 0; index < snaps.length; index += 2) {
    const user = snaps[index];
    const profile = snaps[index + 1];
    const expectedUid = PLAY_REVIEW_FIXTURE_UIDS[index / 2];
    if (
      user.id !== expectedUid ||
      profile.id !== expectedUid ||
      !user.exists ||
      !profile.exists ||
      !isPlayReviewFixtureData(user.data() as Record<string, unknown>) ||
      !isPlayReviewFixtureData(profile.data() as Record<string, unknown>)
    ) {
      throw new HttpsError(
        "failed-precondition",
        "Review fixtures are incomplete. Contact the app developer.",
      );
    }
  }
}

function allIdsAreReviewOnly(value: unknown): boolean {
  if (!Array.isArray(value) || value.length === 0) return false;
  const allowed = new Set<string>(PLAY_REVIEW_ALL_UIDS);
  return value.every((id) => typeof id === "string" && allowed.has(id));
}

async function deleteValidatedReviewDocs(
  firestore: Firestore,
  docs: QueryDocumentSnapshot<DocumentData>[],
  participantField?: string,
): Promise<void> {
  const refs = [];
  for (const doc of docs) {
    const data = doc.data() as Record<string, unknown>;
    if (data.dataPartition !== PLAY_REVIEW_PARTITION) continue;
    if (participantField && !allIdsAreReviewOnly(data[participantField])) {
      logger.error("Refusing mixed-partition review reset", {
        path: doc.ref.path,
      });
      throw new HttpsError("internal", "Review data isolation check failed.");
    }
    refs.push(doc.ref);
  }
  for (let start = 0; start < refs.length; start += 400) {
    const batch = firestore.batch();
    for (const ref of refs.slice(start, start + 400)) batch.delete(ref);
    await batch.commit();
  }
}

function isReviewOnlyUid(value: unknown): value is string {
  return typeof value === "string" &&
    (PLAY_REVIEW_ALL_UIDS as readonly string[]).includes(value);
}

/**
 * Review Bamboo documents live under review-only roots. Public posts/comments
 * carry no author field (P0-3); a legacy one that still does must name a
 * review uid. Likes and private ownership mappings must name a review uid.
 */
function assertReviewBambooDocument(
  data: Record<string, unknown>,
  path: string,
  idField: "ownerUid" | "userId" | null,
): void {
  const legacyAuthor = data.authorId;
  if (
    data.dataPartition !== PLAY_REVIEW_PARTITION ||
    (idField != null && !isReviewOnlyUid(data[idField])) ||
    (legacyAuthor != null && !isReviewOnlyUid(legacyAuthor))
  ) {
    logger.error("Refusing unsafe review Bamboo reset", { path, idField });
    throw new HttpsError("internal", "Review data isolation check failed.");
  }
}

async function deleteRefsInBatches(
  firestore: Firestore,
  refs: DocumentReference[],
): Promise<void> {
  for (let start = 0; start < refs.length; start += 400) {
    const batch = firestore.batch();
    for (const ref of refs.slice(start, start + 400)) batch.delete(ref);
    await batch.commit();
  }
}

async function resetReviewBambooArtifacts(firestore: Firestore): Promise<void> {
  const [posts, postOwners, commentOwners] = await Promise.all([
    firestore.collection(REVIEW_BAMBOO_POSTS_COLLECTION).get(),
    firestore.collection(REVIEW_BAMBOO_POST_AUTHORS_COLLECTION).get(),
    firestore.collection(REVIEW_BAMBOO_COMMENT_AUTHORS_COLLECTION).get(),
  ]);
  const refs: DocumentReference[] = [];

  for (const post of posts.docs) {
    assertReviewBambooDocument(
      post.data() as Record<string, unknown>,
      post.ref.path,
      null,
    );
    const [comments, likes] = await Promise.all([
      post.ref.collection("comments").get(),
      post.ref.collection("likes").get(),
    ]);
    for (const like of likes.docs) {
      assertReviewBambooDocument(
        like.data() as Record<string, unknown>,
        like.ref.path,
        "userId",
      );
      refs.push(like.ref);
    }
    for (const comment of comments.docs) {
      assertReviewBambooDocument(
        comment.data() as Record<string, unknown>,
        comment.ref.path,
        null,
      );
      const commentLikes = await comment.ref.collection("likes").get();
      for (const like of commentLikes.docs) {
        assertReviewBambooDocument(
          like.data() as Record<string, unknown>,
          like.ref.path,
          "userId",
        );
        refs.push(like.ref);
      }
      refs.push(comment.ref);
    }
    refs.push(post.ref);
  }
  for (const mapping of [...postOwners.docs, ...commentOwners.docs]) {
    assertReviewBambooDocument(
      mapping.data() as Record<string, unknown>,
      mapping.ref.path,
      "ownerUid",
    );
    refs.push(mapping.ref);
  }
  await deleteRefsInBatches(firestore, refs);
}

/**
 * Direct-chat heart ledger ids are deterministic.  The review-session reset
 * removes the rooms themselves, so it must remove only these exact, known
 * review ledger documents too; otherwise the next seeded session attempts to
 * create an already-existing ledger record.
 */
async function resetReviewDirectChatHeartTransactions(
  firestore: Firestore,
): Promise<void> {
  const entries = PLAY_REVIEW_FIXTURE_UIDS.map((fixtureUid) => {
    const roomId = buildDirectRoomId(PLAY_REVIEWER_UID, fixtureUid);
    const transactionId = createHash("sha256")
      .update(`direct_chat:${roomId}`)
      .digest("hex");
    return {
      roomId,
      ref: firestore.collection("heartTransactions").doc(transactionId),
    };
  });
  const snaps = await firestore.getAll(...entries.map(({ ref }) => ref));
  const refsToDelete: DocumentReference[] = [];

  for (let index = 0; index < snaps.length; index += 1) {
    const snap = snaps[index];
    if (!snap.exists) continue;
    const data = (snap.data() ?? {}) as Record<string, unknown>;
    const { roomId } = entries[index];
    // Refuse to delete even a deterministically-addressed document unless it
    // proves it belongs to this review-only direct-chat pair.
    if (
      data.uid !== PLAY_REVIEWER_UID ||
      data.feature !== "direct_chat" ||
      data.resourceId !== roomId
    ) {
      throw new HttpsError("internal", "Review data isolation check failed.");
    }
    refsToDelete.push(snap.ref);
  }
  await deleteRefsInBatches(firestore, refsToDelete);
}

async function resetReviewArtifacts(firestore: Firestore): Promise<void> {
  const [fromInteractions, toInteractions, matches, rooms, reports] =
    await Promise.all([
      firestore.collection("interactions")
        .where("fromUserId", "==", PLAY_REVIEWER_UID).get(),
      firestore.collection("interactions")
        .where("toUserId", "==", PLAY_REVIEWER_UID).get(),
      firestore.collection("matches")
        .where("userIds", "array-contains", PLAY_REVIEWER_UID).get(),
      firestore.collection("chat_rooms")
        .where("participantIds", "array-contains", PLAY_REVIEWER_UID).get(),
      firestore.collection("reports")
        .where("reporterId", "==", PLAY_REVIEWER_UID).get(),
    ]);

  const interactionDocs = new Map<string, QueryDocumentSnapshot<DocumentData>>();
  for (const doc of [...fromInteractions.docs, ...toInteractions.docs]) {
    interactionDocs.set(doc.ref.path, doc);
  }
  // Subcollections survive parent deletion in Firestore. Validate every room
  // before clearing its messages so a corrupted mixed room aborts the reset.
  for (const room of rooms.docs) {
    const roomData = room.data() as Record<string, unknown>;
    if (roomData.dataPartition !== PLAY_REVIEW_PARTITION) continue;
    if (!allIdsAreReviewOnly(roomData.participantIds)) {
      throw new HttpsError("internal", "Review data isolation check failed.");
    }
    const messages = await room.ref.collection("messages").get();
    const messageBatch = firestore.batch();
    for (const message of messages.docs) messageBatch.delete(message.ref);
    if (!messages.empty) await messageBatch.commit();
  }
  const reviewMeetingRef = firestore.collection("blindMeetings").doc(REVIEW_MEETING_ID);
  const reviewMeeting = await reviewMeetingRef.get();
  if (reviewMeeting.exists) {
    const meetingData = (reviewMeeting.data() ?? {}) as Record<string, unknown>;
    if (
      meetingData.dataPartition !== PLAY_REVIEW_PARTITION ||
      !allIdsAreReviewOnly(meetingData.participantIds)
    ) {
      throw new HttpsError("internal", "Review data isolation check failed.");
    }
    for (const child of ["participants", "publicProfiles", "matchingResult"]) {
      const children = await reviewMeetingRef.collection(child).get();
      const childBatch = firestore.batch();
      for (const doc of children.docs) childBatch.delete(doc.ref);
      if (!children.empty) await childBatch.commit();
    }
  }
  await deleteValidatedReviewDocs(firestore, [...interactionDocs.values()]);
  await deleteValidatedReviewDocs(firestore, matches.docs, "userIds");
  await deleteValidatedReviewDocs(firestore, rooms.docs, "participantIds");
  await deleteValidatedReviewDocs(firestore, reports.docs);
  await resetReviewBambooArtifacts(firestore);
  await resetReviewDirectChatHeartTransactions(firestore);

  const exactDeletes = [
    firestore.collection("blindMeetingApplications").doc(PLAY_REVIEWER_UID),
    firestore.collection("blindMeetings").doc(REVIEW_MEETING_ID),
    firestore.collection("chat_rooms").doc(REVIEW_GROUP_ROOM_ID),
    firestore.collection("users").doc(PLAY_REVIEWER_UID)
      .collection("recommendationRefreshes").doc(kstDateKey()),
  ];
  const batch = firestore.batch();
  for (const ref of exactDeletes) batch.delete(ref);
  for (const ownerUid of PLAY_REVIEW_ALL_UIDS) {
    for (const targetUid of PLAY_REVIEW_ALL_UIDS) {
      if (ownerUid === targetUid) continue;
      batch.delete(firestore.collection("blocks").doc(ownerUid)
        .collection("targets").doc(targetUid));
    }
  }
  await batch.commit();
}

function fixtureProfileSnapshot(data: Record<string, unknown>): Record<string, unknown> {
  const onboarding = isRecord(data.onboarding) ? data.onboarding : {};
  const interests = Array.isArray(onboarding.interests) ? onboarding.interests : [];
  return {
    userId: normalizedText(data.uid),
    nickname: normalizedText(data.nickname ?? onboarding.nickname),
    department: normalizedText(data.department ?? onboarding.department),
    mbti: normalizedText(data.mbti ?? onboarding.mbti),
    topInterestIds: interests.slice(0, 3),
    avatarSeed: normalizedText(data.uid),
    schoolVerified: true,
    safetyStampSummary: {
      completedMeetings: 0,
      allCheckinsCompleted: false,
      allCheckoutsCompleted: false,
    },
    oneLineIntro: normalizedText(
      onboarding.selfIntroduction ?? onboarding.bio ?? data.bio,
    ),
  };
}

