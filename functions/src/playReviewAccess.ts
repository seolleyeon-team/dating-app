function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function readCallableData(value: unknown): Record<string, unknown> {
  return isRecord(value) ? value : {};
}

function normalizedText(value: unknown): string {
  return typeof value === "string" ? value.trim() : "";
}

function fixedTimeTextEqual(left: string, right: string): boolean {
  const leftDigest = createHash("sha256").update(left, "utf8").digest();
  const rightDigest = createHash("sha256").update(right, "utf8").digest();
  return timingSafeEqual(leftDigest, rightDigest);
}

/**
 * Secret format generated by scripts/generate_play_review_password_hash.js:
 * `scrypt-v1:<salt-base64>:<derived-key-base64>`.
 */
export function verifyPlayReviewPassword(
  password: string,
  encodedSecret: string,
): boolean {
  const [version, saltBase64, expectedBase64, extra] = encodedSecret.split(":");
  if (
    version !== "scrypt-v1" ||
    !saltBase64 ||
    !expectedBase64 ||
    extra !== undefined
  ) {
    return false;
  }
  try {
    const salt = Buffer.from(saltBase64, "base64");
    const expected = Buffer.from(expectedBase64, "base64");
    if (salt.length < 16 || expected.length !== SCRYPT_KEY_LENGTH) return false;
    const actual = scryptSync(password, salt, SCRYPT_KEY_LENGTH, {
      N: 16384,
      r: 8,
      p: 1,
      maxmem: 64 * 1024 * 1024,
    });
    return timingSafeEqual(actual, expected);
  } catch {
    return false;
  }
}

export function isPlayReviewUserData(
  data: Record<string, unknown> | null | undefined,
): boolean {
  return !!data &&
    data.accountType === PLAY_REVIEW_ACCOUNT_TYPE &&
    data.dataPartition === PLAY_REVIEW_PARTITION &&
    data.reviewAccess === true &&
    data.reviewProfileReady === true;
}

export function isPlayReviewFixtureData(
  data: Record<string, unknown> | null | undefined,
): boolean {
  return !!data &&
    data.accountType === PLAY_REVIEW_FIXTURE_ACCOUNT_TYPE &&
    data.dataPartition === PLAY_REVIEW_PARTITION &&
    data.reviewFixtureEnabled === true;
}

/**
 * Fixtures intentionally have `loginDisabled: true` so they cannot become
 * real sign-in accounts. That flag must not prevent the one fixed reviewer
 * session from opening a review-only direct chat with them.
 */
export function canPlayReviewUserOpenDirectChatWithFixture(
  userData: Record<string, unknown> | null | undefined,
  partnerData: Record<string, unknown> | null | undefined,
): boolean {
  return isPlayReviewUserData(userData) && isPlayReviewFixtureData(partnerData);
}

export function dataPartitionOf(
  data: Record<string, unknown> | null | undefined,
): "production" | "play_review" | "invalid" {
  const value = data?.dataPartition;
  if (value === undefined || value === null || value === "production") {
    return "production";
  }
  return value === PLAY_REVIEW_PARTITION ? PLAY_REVIEW_PARTITION : "invalid";
}

function kstDateKey(now = new Date()): string {
  const kst = new Date(now.getTime() + 9 * 60 * 60 * 1000);
  const year = kst.getUTCFullYear().toString();
  const month = (kst.getUTCMonth() + 1).toString().padStart(2, "0");
  const day = kst.getUTCDate().toString().padStart(2, "0");
  return `${year}${month}${day}`;
}

function kstIsoDate(now = new Date()): string {
  const key = kstDateKey(now);
  return `${key.slice(0, 4)}-${key.slice(4, 6)}-${key.slice(6, 8)}`;
}

